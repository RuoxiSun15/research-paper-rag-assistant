"""Convert Azure Document Intelligence figures into RAG-ready metadata."""

import re
from pathlib import Path
from typing import Any, Dict, Iterable, List

from src.data_pipeline.vision_analyzer import (
    format_vision_analysis,
    is_meaningful_figure_image,
)


def extract_figures(figures: Iterable[Any]) -> List[Dict[str, Any]]:
    """Return serializable figure metadata from an analysis result."""
    extracted: List[Dict[str, Any]] = []

    for index, figure in enumerate(figures or [], start=1):
        caption = getattr(figure, "caption", None)
        bounding_regions = []
        for region in getattr(figure, "bounding_regions", None) or []:
            bounding_regions.append(
                {
                    "page_number": getattr(region, "page_number", None),
                    "polygon": list(getattr(region, "polygon", None) or []),
                }
            )

        figure_id = getattr(figure, "id", None) or f"figure_{index}"
        extracted.append(
            {
                "figure_id": figure_id,
                "caption": getattr(caption, "content", "") or "",
                "caption_elements": list(
                    getattr(caption, "elements", None) or []
                ),
                "page_numbers": [
                    region["page_number"] for region in bounding_regions
                    if region["page_number"] is not None
                ],
                "bounding_regions": bounding_regions,
                "elements": list(getattr(figure, "elements", None) or []),
                "image_path": None,
            }
        )

    return extracted


def save_figure_images(
    client: Any,
    result_id: str,
    figures: List[Dict[str, Any]],
    output_dir: Path,
    model_id: str = "prebuilt-layout",
) -> List[Dict[str, Any]]:
    """Download figure PNGs generated by Document Intelligence."""
    output_dir.mkdir(parents=True, exist_ok=True)

    for figure in figures:
        figure_id = figure["figure_id"]
        safe_id = re.sub(r"[^A-Za-z0-9_.-]", "_", figure_id)
        image_path = output_dir / f"{safe_id}.png"
        image_bytes = client.get_analyze_result_figure(
            model_id=model_id,
            result_id=result_id,
            figure_id=figure_id,
        )
        image_path.write_bytes(b"".join(image_bytes))
        figure["image_path"] = str(image_path.absolute())

    return figures


def build_figure_chunks(
    figures: Iterable[Dict[str, Any]],
    metadata: Dict[str, Any],
    start_index: int = 0,
) -> List[Dict[str, Any]]:
    """Create searchable chunks from figure captions and locations."""
    chunks: List[Dict[str, Any]] = []
    source_file = metadata.get("source_file", "unknown")
    safe_source = re.sub(r"[^A-Za-z0-9_\-=]", "_", source_file)

    for offset, figure in enumerate(figures or []):
        image_path = figure.get("image_path")
        if (
            image_path
            and Path(image_path).exists()
            and not is_meaningful_figure_image(image_path)
        ):
            continue
        chunk_index = start_index + offset
        figure_id = str(figure.get("figure_id", chunk_index))
        safe_figure_id = re.sub(r"[^A-Za-z0-9_\-=]", "_", figure_id)
        page_numbers = figure.get("page_numbers") or []
        page_text = ", ".join(str(page) for page in page_numbers) or "unknown"
        caption = figure.get("caption") or "No caption detected"
        vision_text = format_vision_analysis(figure.get("vision_analysis") or {})
        content = (
            f"Figure on page(s) {page_text}.\n"
            f"Caption: {caption}"
        )
        if vision_text:
            content += f"\n{vision_text}"

        chunk_metadata = metadata.copy()
        chunk_metadata.update(
            {
                "chunk_index": chunk_index,
                "chunk_size": len(content),
                "content_type": "figure",
                "page_number": page_numbers[0] if page_numbers else None,
                "figure_id": figure.get("figure_id"),
                "figure_caption": caption,
                "figure_image_path": figure.get("image_path"),
                "figure_type": (figure.get("vision_analysis") or {}).get(
                    "figure_type"
                ),
                "figure_visual_summary": (
                    figure.get("vision_analysis") or {}
                ).get("summary"),
            }
        )
        chunks.append(
            {
                "content": content,
                "metadata": chunk_metadata,
                "chunk_id": f"{safe_source}_{safe_figure_id}",
            }
        )

    return chunks
